interface PlatformLogoProps {
  platform: CandidatePlatform | string;
  /** Pixel size of the square mark. */
  size?: number;
  /** 'brand' paints the official colour; 'mono' inherits `currentColor` (for dark / selected chips). */
  tone?: 'brand' | 'mono';
  className?: string;
}

export function PlatformLogo({ platform, size = 16, tone = 'brand', className = '' }: PlatformLogoProps) {
  const id = normalizePlatform(platform);
  const meta = id ? getPlatformMeta(id) : null;
  const color = tone === 'mono' || !meta ? 'currentColor' : meta.brandColor;
  const label = meta?.label ?? String(platform);

  if (!id || id === 'Resumes' || id === 'MultiSite') {
    const Glyph = id === 'MultiSite' ? Layers : FileText;
    return (
      <Glyph
        aria-label={label}
        role="img"
        width={size}
        height={size}
        strokeWidth={2.25}
        className={`flex-shrink-0 ${className}`}
        style={{ color }}
      />
    );
  }

  return (
    <svg
      role="img"
      aria-label={label}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={`flex-shrink-0 ${className}`}
      style={{ color }}
    >
      <path d={BRAND_PATHS[id]} fill="currentColor" />
    </svg>
  );
}

interface PlatformBadgeProps {
  platform: CandidatePlatform | string;
  /** 'light' (default) is the hairline chip with the brand-coloured mark; 'ink' inverts it for dark surfaces. */
  variant?: 'light' | 'ink';
  size?: 'xs' | 'sm';
  className?: string;
}

/** Logo + label chip. Hairline chip with the brand mark in brand colour, per the design system's "chips, not pills" rule. */
export function PlatformBadge({ platform, variant = 'light', size = 'xs', className = '' }: PlatformBadgeProps) {
  const id = normalizePlatform(platform);
  const label = id ? getPlatformMeta(id).label : String(platform);
  const sizing = size === 'xs' ? 'h-[22px] px-2 text-body-xs gap-1.5' : 'h-7 px-2.5 text-body-sm gap-2';
  const skin = variant === 'ink' ? 'bg-ink text-white border-ink' : 'bg-elevated text-body border-hairline';

  return (
    <span className={`inline-flex items-center rounded-sm border font-medium whitespace-nowrap ${sizing} ${skin} ${className}`}>
      <PlatformLogo platform={platform} size={size === 'xs' ? 11 : 13} tone={variant === 'ink' ? 'mono' : 'brand'} />
      <span>{label}</span>
    </span>
  );
}
